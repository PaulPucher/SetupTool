# Phase 1 -- golden-value regression on the full production chain and on
# the recommendation engine, at the PRIMARY sideslip_source
# (ekf_auto_pacejka, production default since 2026-09-01 -- thesis_notes.md
# "Production sideslip source set to ekf_auto_pacejka"). "kinematic" and
# "ekf_auto_dugoff" get the same kind of golden coverage as SECONDARY,
# explicit-mode regression sets in tests/test_golden_auto_modes.py instead
# of here -- this file no longer needs to flip the live config to
# "kinematic" to run, since tests/conftest.py's pipeline_result fixture
# now asserts and uses whatever the live config's sideslip_source is
# (expected to be "ekf_auto_pacejka").
#
# THESE ARE REGRESSION TESTS, NOT CORRECTNESS TESTS. They pin CURRENT
# output (tests/golden/*.json, generated by tests/generate_golden.py) so
# a future code change that alters the numbers is VISIBLE. A passing
# suite means "nothing changed unintentionally" -- it never means "the
# numbers are correct". Some of what is pinned here may still be wrong;
# thesis_notes.md and PLAN.md's own record of known limitations (the
# kinematic sideslip circularity underlying the tyre curve this auto-fit
# still starts from, the CS_ratio cross-lap aggregation ceiling-clipping
# problem, the un-re-derived thresholds -- classification.thresholds_
# calibrated_for_sideslip_source is still "kinematic", so the [UNCAL]
# banner is expected here) are exactly the kind of thing a golden test
# happily pins without endorsing.
#
# Golden files record: git commit hash, generation timestamp, and the
# exact configuration (sideslip_source, accuracy cap, config snapshot) --
# see tests/generate_golden.py and each golden file's own "_meta" block,
# so a future failure can be attributed to either a real behaviour change
# or a deliberate, intentional regeneration.
#
# Float tolerance and NaN handling: see tests/_json_utils.py's own
# docstring/comments for the full rationale (combined relative+absolute
# tolerance, rtol=1e-6/atol=1e-9; NaN==NaN passes, NaN-vs-number fails).

import json

import pytest

from tests._json_utils import diff_json

PIPELINE_GOLDEN_PATH = "tests/golden/pipeline_dubai_ekf_auto_pacejka_cap1.json"
RECOMMENDATIONS_GOLDEN_PATH = "tests/golden/recommendations_dubai_ekf_auto_pacejka_cap1.json"


def _load_golden(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        pytest.fail(
            f"{path} not found -- run `python -m tests.generate_golden` first "
            "(deliberately, not automatically: see that script's own docstring)."
        )


def test_golden_file_metadata_present():
    """The golden file's own self-description must be complete enough to
    attribute a future failure -- checked directly, not assumed."""
    golden = _load_golden(PIPELINE_GOLDEN_PATH)
    meta = golden.get("_meta", {})
    for key in ("git_commit_hash", "generated_at_utc", "data_file",
                "sideslip_source", "accuracy_cap"):
        assert key in meta and meta[key] not in (None, ""), f"golden file _meta missing/empty {key!r}"
    assert meta["sideslip_source"] == "ekf_auto_pacejka"
    assert meta["accuracy_cap"] == 1


def test_pipeline_did_not_fall_back(pipeline_result):
    """A golden comparison against a FALLBACK run would silently pin
    kinematic numbers under the ekf_auto_pacejka label -- checked
    explicitly, same rationale as tests/test_golden_auto_modes.py's own
    test_secondary_mode_did_not_fall_back."""
    assert not pipeline_result["fallback_used"], (
        f"ekf_auto_pacejka fell back to kinematic on this run ({pipeline_result['fallback_reason']}) -- "
        "the golden comparison below would be meaningless under fallback"
    )


def test_pipeline_output_matches_golden(pipeline_result):
    """summarise_corners' complete output, recomputed now, against the
    pinned golden snapshot."""
    golden = _load_golden(PIPELINE_GOLDEN_PATH)
    got = {"summaries": pipeline_result["summaries"]}
    expected = {"summaries": golden["summaries"]}
    diffs = diff_json(got, expected)
    assert not diffs, (
        f"{len(diffs)} field(s) differ from {PIPELINE_GOLDEN_PATH} "
        f"(golden generated at commit {golden['_meta']['git_commit_hash']}, "
        f"{golden['_meta']['generated_at_utc']}):\n" +
        "\n".join(f"  {p}: got={a!r} expected={b!r}" for p, a, b in diffs[:30]) +
        (f"\n  ... and {len(diffs) - 30} more" if len(diffs) > 30 else "")
    )


def test_pipeline_corner_count_matches_golden(pipeline_result):
    """Cheap, fast-failing sanity check ahead of the full field-by-field
    diff above -- if this fails, the diff above will be enormous and this
    gives a faster, clearer first signal (corner detection/count changed,
    not just some numeric field)."""
    golden = _load_golden(PIPELINE_GOLDEN_PATH)
    assert len(pipeline_result["summaries"]) == len(golden["summaries"])


def test_recommendations_output_matches_golden(pipeline_result):
    """Same regression check for the recommendation engine's output on
    the same outing/configuration. Reuses OutingForm._classify_corner
    unmodified (self=None call, the same precedent core/weekend_pdf_
    export.py already uses in production) so this test can never
    silently drift from what the app itself would classify -- see
    tests/generate_golden.py for why this needs importing ui/views/
    outing_form.py despite the rest of this suite staying Qt-free.
    """
    try:
        from ui.views.outing_form import OutingForm
    except ImportError as e:
        pytest.skip(f"ui.views.outing_form not importable in this environment ({e}) -- "
                     "recommendation-engine golden check skipped, see report 'chose not to do'")

    from modules.recommendation import generate_recommendations, load_recommendations_config

    def classify_fn(summary):
        return OutingForm._classify_corner(None, summary)

    golden = _load_golden(RECOMMENDATIONS_GOLDEN_PATH)
    rec_config = load_recommendations_config()
    results = generate_recommendations(
        pipeline_result["summaries"], classify_fn, feedback_data={}, setup_data=None,
        config=rec_config, outing=None, driving_level=None,
    )
    diffs = diff_json({"recommendations": results}, {"recommendations": golden["recommendations"]})
    assert not diffs, (
        f"{len(diffs)} field(s) differ from {RECOMMENDATIONS_GOLDEN_PATH}:\n" +
        "\n".join(f"  {p}: got={a!r} expected={b!r}" for p, a, b in diffs[:30])
    )
