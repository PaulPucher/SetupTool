# fig:comparison_matrix -- the two evaluation outcomes per session in one
# view: driver statement (tab:feedback) and setup change (tab:setup_comparison)
# as one symbol each, the tire age below. The outcomes are the author's
# assignments in those two thesis tables, not computed here; they are copied
# into OUTCOMES and checked against the session list of fig_session_overview,
# whose CSV also supplies the tire age (outing field, km). The symbol shape
# carries the outcome, so the figure reads in black and white.
# No session is loaded.
# Run: python -m tools.thesis_figures.fig_comparison_matrix [--tag final] [--out DIR] | --render-only

import argparse

from tools.thesis_figures import common

SCRIPT = "fig_comparison_matrix"
# (session, driver statement, setup change) as in tab:feedback / tab:setup_comparison
OUTCOMES = (
    ("NBR 1", "contradict", "unmatched"), ("NBR 2", "contradict", "unmatched"),
    ("NBR 3", "contradict", "agree"), ("NBR 4", "agree", "unmatched"),
    ("NBR 5", "agree", "contradict"), ("PRC 1", "contradict", "contradict"),
    ("PRC 2", "agree", "partly"), ("PRC 3", "partly", "partly"),
    ("PRC 4", "agree", "unmatched"), ("PRC 5", "contradict", "unmatched"),
)
ROWS = (("driver", "driver statement"), ("setup", "setup change"))
KINDS = ("agree", "partly", "contradict", "unmatched")
COL_W, TRACK_GAP, ROW_H = 1.15, 0.5, 0.75   # cm; layout only
R = "2.6pt"   # symbol radius
PICS = {
    "agree": f"\\fill (0,0) circle ({R});",
    "partly": f"\\fill (0,{R}) arc (90:270:{R}) -- cycle; \\draw[line width=0.6pt] (0,0) circle ({R});",
    "contradict": f"\\draw[line width=1pt] (-{R},-{R}) -- ({R},{R}) (-{R},{R}) -- ({R},-{R});",
    "unmatched": f"\\draw[line width=0.6pt] (-{R},-{R}) rectangle ({R},{R});",
}


def build(tag="dev", out=None):
    data_dir, _plots, _prefix = common.out_dirs(out)
    m, ov = common.read_csv(f"{data_dir}/fig_session_overview.csv")
    if [s for s, _d, _c in OUTCOMES] != ov["session"]:
        raise common.Refused(f"{SCRIPT}: session order differs from fig_session_overview.csv ({ov['session']})")
    for _s, d, c in OUTCOMES:
        if d not in KINDS or c not in KINDS:
            raise common.Refused(f"{SCRIPT}: unknown outcome {d!r} / {c!r}")
    cols = {"session": [s for s, _d, _c in OUTCOMES], "driver": [d for _s, d, _c in OUTCOMES],
            "setup": [c for _s, _d, c in OUTCOMES], "tyre_age_km": ov["tyre_age_km"]}
    common.write_csv(f"{data_dir}/{SCRIPT}.csv", cols,
                     common.meta(SCRIPT, m["outing_ids"].split(","), tag,
                                 source="outcomes as assigned in tab:feedback and tab:setup_comparison; "
                                        "tire age from fig_session_overview.csv (outing field)"))
    render(out)
    return cols


def render(out=None):
    data_dir, plots_dir, _prefix = common.out_dirs(out)
    _m, c = common.read_csv(f"{data_dir}/{SCRIPT}.csv")
    xs, x = [], 0.0
    for i, s in enumerate(c["session"]):
        if i and s.split()[0] != c["session"][i - 1].split()[0]:
            x += TRACK_GAP
        xs.append(x)
        x += COL_W
    t = ["% generated by tools/thesis_figures/fig_comparison_matrix.py -- do not edit; re-run the script\n",
         "\\begin{tikzpicture}[font=\\small,\n"]
    t += [f"  cmp {k}/.pic={{{v}}},\n" for k, v in PICS.items()]
    t.append("  rowlabel/.style={anchor=east, inner sep=0pt}]\n")
    lx = -0.5 * COL_W - 0.25
    for i, s in enumerate(c["session"]):
        t.append(f"\\node[anchor=south] at ({xs[i]:.2f},0.35) {{{common.tex_escape(s)}}};\n")
    for r, (key, word) in enumerate(ROWS):
        y = -r * ROW_H
        t.append(f"\\node[rowlabel] at ({lx:.2f},{y:.2f}) {{{word}}};\n")
        for i, v in enumerate(c[key]):
            t.append(f"\\pic at ({xs[i]:.2f},{y:.2f}) {{cmp {v}}};\n")
    y = -len(ROWS) * ROW_H
    t.append(f"\\node[rowlabel] at ({lx:.2f},{y:.2f}) {{tire age in km}};\n")
    for i, v in enumerate(c["tyre_age_km"]):
        t.append(f"\\node at ({xs[i]:.2f},{y:.2f}) {{{'--' if v == '-' else v}}};\n")
    # thin rules between header, outcome rows and tire age
    x0, x1 = lx - 2.9, xs[-1] + 0.5 * COL_W
    for yr in (0.35, -(len(ROWS) - 0.5) * ROW_H):
        t.append(f"\\draw[auxGray, thin] ({x0:.2f},{yr:.2f}) -- ({x1:.2f},{yr:.2f});\n")
    # legend row
    yl = y - 0.85
    lxs = 0.0
    for k in KINDS:
        t.append(f"\\pic at ({lx - 2.6 + lxs:.2f},{yl:.2f}) {{cmp {k}}};\n"
                 f"\\node[anchor=west] at ({lx - 2.6 + lxs + 0.15:.2f},{yl:.2f}) {{{k}}};\n")
        lxs += 2.3
    t.append("\\end{tikzpicture}%\n")
    common.write_tex(f"{plots_dir}/{SCRIPT}.tex", "".join(t))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tag", default="dev")
    ap.add_argument("--out")
    ap.add_argument("--render-only", action="store_true", help="write the .tex from the existing CSV only")
    a = ap.parse_args(argv)
    if a.render_only:
        render(a.out)
    else:
        build(a.tag, a.out)


if __name__ == "__main__":
    main()
