# fig:inst_tire_age -- per session the share of per-lap cells with open-loop
# instability over the tire age. Same population as fig_session_overview
# (stored setup_engine.data_layer.session.cells, INST k / n over the cells
# with a stability value), read from its CSV together with the tire age
# (outing field, km). Descriptive only: ten sessions, two tracks, no fit.
# No session is loaded.
# Run: python -m tools.thesis_figures.fig_inst_tire_age [--tag final] [--out DIR] | --render-only

import argparse

from tools.thesis_figures import common

SCRIPT = "fig_inst_tire_age"
TRACK_STYLE = {"NBR": "trackNBR, mark=*, mark size=2pt", "PRC": "trackPRC, mark=square*, mark size=1.9pt"}
# labels above the point; on the zero line they stand vertical and hang
# below it (five sessions share it within 100 km, and PRC 3 sits just above
# PRC 1), in a strip below zero kept free of ticks. PRC 2 / PRC 5 sit
# close: left / right; NBR 5 to the right, clear of the axis
LABEL_ANCHOR = {"PRC 2": "south east", "PRC 3": "south", "PRC 5": "south west", "NBR 5": "south west"}
ZERO_STRIP = 0.30   # share of the y range below zero for the hanging labels; layout only


def build(tag="dev", out=None):
    data_dir, _plots, _prefix = common.out_dirs(out)
    m, ov = common.read_csv(f"{data_dir}/fig_session_overview.csv")
    cols = {"session": ov["session"], "track": [s.split()[0] for s in ov["session"]],
            "tyre_age_km": ov["tyre_age_km"], "inst_k": ov["inst_k"], "inst_n": ov["inst_n"],
            "inst_share_pct": [100 * common.num(v) for v in ov["inst_share"]]}
    common.write_csv(f"{data_dir}/{SCRIPT}.csv", cols,
                     common.meta(SCRIPT, m["outing_ids"].split(","), tag,
                                 source="fig_session_overview.csv: INST k / n of the stored session cells, "
                                        "tire age (outing field)"))
    render(out)
    return cols


def render(out=None):
    data_dir, plots_dir, _prefix = common.out_dirs(out)
    _m, c = common.read_csv(f"{data_dir}/{SCRIPT}.csv")
    pts = [(s, tr, common.num(a), common.num(y)) for s, tr, a, y in
           zip(c["session"], c["track"], c["tyre_age_km"], c["inst_share_pct"]) if a != "-"]
    y_max = max(y for *_r, y in pts) * 1.3
    y_min = -ZERO_STRIP * y_max
    t = ["% generated by tools/thesis_figures/fig_inst_tire_age.py -- do not edit; re-run the script\n",
         "\\begin{tikzpicture}\n",
         "\\begin{axis}[thesis axis, width=0.7\\textwidth, height=0.42\\textwidth, clip=false,\n"
         f"  xmin=-8, xmax=175, ymin={y_min:.2f}, ymax={y_max:.2f}, ytick={{0,2,...,{int(y_max)}}},\n"
         "  xlabel={tire age in km}, ylabel={open-loop unstable cells in \\%},\n"
         "  yticklabel style={/pgf/number format/fixed},\n"
         "  legend style={at={(0.98,0.97)}, anchor=north east, cells={anchor=west}}]\n"]
    for tr in ("NBR", "PRC"):
        coords = " ".join(f"({a:g},{y:.3f})" for _s, t_, a, y in pts if t_ == tr)
        t.append(f"\\addplot[{TRACK_STYLE[tr]}, only marks] coordinates {{{coords}}};\n\\addlegendentry{{{tr}}}\n")
    for s, _t, a, y in pts:
        pos = "anchor=east, rotate=90" if y == 0 else f"anchor={LABEL_ANCHOR.get(s, 'south')}"
        t.append(f"\\node[{pos}, font=\\footnotesize, inner sep=2.5pt] "
                 f"at (axis cs:{a:g},{y:.3f}) {{{common.tex_escape(s)}}};\n")
    t.append("\\end{axis}\n\\end{tikzpicture}%\n")
    common.write_tex(f"{plots_dir}/{SCRIPT}.tex", "".join(t))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tag", default="dev")
    ap.add_argument("--out")
    ap.add_argument("--render-only", action="store_true", help="write the .tex from the existing CSV only")
    a = ap.parse_args(argv)
    if a.render_only:
        render(a.out)
    else:
        build(a.tag, a.out)


if __name__ == "__main__":
    main()
