# fig:beta_washout -- the kinematic sideslip angle over one lap: the plain
# integral of beta_dot = a_y / v - yaw rate (restarted at the lap start, so
# the drift of one lap is visible) against the chain's kinematic beta,
# estimate_sideslip: the integral over the whole session through a
# Butterworth high-pass (BUTTERWORTH_ORDER, stability_estimation.
# beta_washout_cutoff_hz, filtfilt zero-phase), zero below the moving speed.
# The kinematic beta is the fit-L input and the fallback path; the observer
# beta of the analysis is not drawn. No analysis re-run: only
# prepare_vehicle_state and estimate_sideslip.
# Run: python -m tools.thesis_figures.fig_beta_washout --outing 26 --lap 15 [--tag r2] [--out DIR] [--render-only]

import argparse

import numpy as np

from tools.thesis_figures import common

SCRIPT = "fig_beta_washout"
AXIS_WIDTH = "0.86\\textwidth"
PANEL_HEIGHT = "0.3\\textwidth"


def build(outing, lap, tag="dev", out=None):
    from modules.stability_analysis import BUTTERWORTH_ORDER, estimate_sideslip, prepare_vehicle_state
    session = common.load_session(outing)
    p = session["params"]
    se = p["stability_estimation"]
    st = prepare_vehicle_state(session["parsed"]["channels"], p)
    t, sr, mv = st["time"], st["sample_rate_hz"], st["moving_mask"]
    lap_row = [l for l in session["parsed"]["laps"] if l["lap_number"] == lap]
    if not lap_row:
        raise common.Refused(f"lap {lap}: not in the session")
    on = np.flatnonzero((t >= lap_row[0]["start_time"]) & (t <= lap_row[0]["end_time"]))
    # beta_dot exactly as estimate_sideslip forms it
    v_safe = np.where(mv, st["v_mps"], 1.0)
    beta_dot = np.where(mv, st["ay_mps2"] / v_safe - st["yaw_rate_radps"], 0.0)
    # the session integral, as estimate_sideslip forms it before the high-pass;
    # the panel shows it offset to zero at the lap start (the in-lap drift)
    session_int = np.cumsum(beta_dot) / sr
    plain = session_int[on] - session_int[on[0]]
    drift_session = float(np.degrees(session_int[on[-1]]))
    washed = estimate_sideslip(st, p)[on]
    s = st["s_m"][on]
    # lap_distance can reset a few samples before the lap table's end time;
    # the plot stops there, the drift is still read at the lap table's end
    # (the reset sample itself is NaN, so compare with the running maximum)
    finite = np.isfinite(s)
    back = np.flatnonzero(finite & (s < np.fmax.accumulate(np.where(finite, s, -np.inf)) - 1.0))
    n_plot = int(back[0]) if back.size else on.size
    keep = np.arange(n_plot)[::max(1, int(np.ceil(n_plot / common.SCATTER_CAP)))]
    if keep[-1] != n_plot - 1:
        keep = np.append(keep, n_plot - 1)
    keep = keep[np.isfinite(s[keep])]
    cols = {"s_m": s[keep], "beta_plain_deg": np.degrees(plain[keep]), "beta_washout_deg": np.degrees(washed[keep])}
    drift = float(np.degrees(plain[-1]))
    label = common.session_label(session["row"])
    common.write_label_map(tag, [outing])
    data_dir, _plots, _prefix = common.out_dirs(out)
    m = common.meta(SCRIPT, [outing], tag, session_label=label, lap=lap,
                    plain="session integral of a_y / v - yaw rate, offset to zero at the lap start",
                    washout=f"Butterworth high-pass order {BUTTERWORTH_ORDER}, {se['beta_washout_cutoff_hz']:g} Hz "
                            "(stability_estimation.beta_washout_cutoff_hz), filtfilt zero-phase, on the session integral",
                    drift_in_lap_deg=f"{drift:.2f} (lap end minus lap start)",
                    drift_since_session_start_deg=f"{drift_session:.2f} (session integral at the lap end)",
                    n_lap_samples=on.size, thinning=f"every {keep[1] - keep[0]}th sample")
    common.write_csv(f"{data_dir}/{SCRIPT}.csv", cols, m)
    render(out)
    return {"drift_in_lap_deg": drift, "drift_session_deg": drift_session, "lap_samples": int(on.size), "n": int(keep.size),
            "washout_range_deg": (float(cols["beta_washout_deg"].min()), float(cols["beta_washout_deg"].max()))}


def render(out=None):
    import re
    data_dir, plots_dir, prefix = common.out_dirs(out)
    meta, raw = common.read_csv(f"{data_dir}/{SCRIPT}.csv")
    sv = [common.num(x) for x in raw["s_m"]]
    s = (min(sv), max(sv))
    fc =re.search(r"\d+(?:\.\d+)? Hz", meta["washout"]).group(0)
    t = ["% generated by tools/thesis_figures/fig_beta_washout.py -- do not edit; re-run the script\n",
         "\\begin{tikzpicture}\n", common.table_read(prefix, f"{SCRIPT}.csv", "tblWash"),
         f"\\begin{{axis}}[thesis axis, scale only axis, width={AXIS_WIDTH}, height={PANEL_HEIGHT},\n"
         f"  xmin={s[0]:.0f}, xmax={s[-1]:.0f}, xlabel={{$s$ in m}}, ylabel={{$\\beta_\\mathrm{{kin}}$ in deg}},\n"
         "  xticklabel style={/pgf/number format/.cd, fixed, set thousands separator={}},\n"
         "  legend style={font=\\small, cells={anchor=west}, at={(0.01,0.97)}, anchor=north west}]\n",
         f"\\addplot[black, thin, densely dotted, forget plot] coordinates {{({s[0]:.0f},0) ({s[-1]:.0f},0)}};\n",
         "\\addplot[auxGray, thick] table[x=s_m, y=beta_plain_deg]{\\tblWash};\n"
         "\\addlegendentry{plain integral (from the lap start)}\n",
         "\\addplot[black, thick] table[x=s_m, y=beta_washout_deg]{\\tblWash};\n"
         f"\\addlegendentry{{after the high-pass ({fc}, zero-phase)}}\n",
         "\\end{axis}\n\\end{tikzpicture}\n"]
    common.write_tex(f"{plots_dir}/{SCRIPT}.tex", "".join(t))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outing", type=int)
    ap.add_argument("--lap", type=int)
    ap.add_argument("--tag", default="dev")
    ap.add_argument("--out")
    ap.add_argument("--render-only", action="store_true")
    a = ap.parse_args(argv)
    if a.render_only:
        render(a.out)
        return
    if None in (a.outing, a.lap):
        ap.error("--outing and --lap are required unless --render-only")
    print(build(a.outing, a.lap, a.tag, a.out))


if __name__ == "__main__":
    main()
