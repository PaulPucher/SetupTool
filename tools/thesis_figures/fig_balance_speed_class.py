# fig:balance_speed_class -- per session the share of corner x phase x lap
# cells with front limiting (US), rear limiting (OS) and open-loop
# instability (INST), split by speed class, for ordered (before, after)
# session pairs side by side (one panel per pair). The cell definition is
# the engine's own: setup_engine.cell_shares on the session's summaries of
# that speed class (US: front CS beyond -margin_f, OS: rear beyond
# -margin_r, INST: dMz/dbeta below the threshold; each symptom over the
# cells that carry its value). Grey fill per symptom, solid outline =
# before, dashed outline = after (no patterns library). Denominators per
# bar in the counts CSV. Stored payloads only.
# Run: python -m tools.thesis_figures.fig_balance_speed_class --pair 13,14 [--pair 11,12] [--tag r2]
#      [--allow-status] [--allow-excluded] [--out DIR]

import argparse

from tools.thesis_figures import common
from tools.thesis_figures.fig_k_sessions import collect

SCRIPT = "fig_balance_speed_class"
SPEED = ("low", "medium", "high")
SYMPTOMS = (("US", "black!10", "front limiting"), ("OS", "black!35", "rear limiting"),
            ("INST", "black!65", "open-loop unstable"))


def shares(summaries):
    from modules.setup_engine import cell_shares
    out = {}
    for sp in SPEED:
        sub = [s for s in summaries if s.get("speed_class") == sp]
        out[sp] = cell_shares(sub) if sub else {k: {"k": 0, "n": 0, "share": None} for k, _g, _w in SYMPTOMS}
    return out


def build(pairs, tag="dev", allow_status=False, allow_excluded=False, out=None):
    outings = [o for p in pairs for o in p]
    rows = {o: (s, k) for o, s, _m, k in collect(outings, allow_status, allow_excluded)}
    common.write_label_map(tag, outings)
    data_dir, plots_dir, prefix = common.out_dirs(out)
    counts = {k: [] for k in ("pair", "label", "role", "speed_class", "symptom", "k", "n", "share")}
    panels = []
    for i, (a, b) in enumerate(pairs, start=1):
        wide = {"x": [1, 2, 3], "speed_class": list(SPEED)}
        title = []
        for role, o in (("before", a), ("after", b)):
            session, _marks = rows[o]
            payload, _why = common.stored_payload(session)
            label = common.session_label(session["row"])
            title.append(label)
            sh = shares(payload["summaries"])
            for sym, _g, _w in SYMPTOMS:
                wide[f"{sym.lower()}_{role}"] = [sh[sp][sym]["share"] if sh[sp][sym]["share"] is not None
                                                 else float("nan") for sp in SPEED]
                for sp in SPEED:
                    c = sh[sp][sym]
                    for k, v in zip(counts, (i, label, role, sp, sym, c["k"], c["n"],
                                             c["share"] if c["share"] is not None else float("nan"))):
                        counts[k].append(v)
        marks = [f"{common.session_label(rows[o][0]['row'])}: {k}" for o in (a, b) for k in rows[o][1]]
        common.write_csv(f"{data_dir}/{SCRIPT}_p{i}.csv", {k: [float(x) if not isinstance(x, str) else x for x in v]
                                                            for k, v in wide.items()},
                         common.meta(SCRIPT, [a, b], tag, marks, pair=f"{title[0]} -> {title[1]}",
                                     cell="engine cell_shares per speed class; denominators in the counts CSV"))
        panels.append((f"p{i}", title))
    common.write_csv(f"{data_dir}/{SCRIPT}_counts.csv", counts, common.meta(SCRIPT, outings, tag))
    common.write_tex(f"{plots_dir}/{SCRIPT}.tex", _tex(prefix, panels))
    return counts


def _macro(key):
    # TeX control sequences take letters only: p1 -> A, p2 -> B, ...
    return chr(ord("A") + int(key[1:]) - 1)


def _tex(prefix, panels):
    n = len(panels)
    t = ["% generated by tools/thesis_figures/fig_balance_speed_class.py -- do not edit; re-run the script\n",
         "\\begin{tikzpicture}\n"]
    for key, _title in panels:
        t.append(common.table_read(prefix, f"{SCRIPT}_{key}.csv", f"tblBal{_macro(key)}"))
    t.append(f"\\begin{{groupplot}}[group style={{group size={n} by 1, horizontal sep=0.9cm}},\n"
             # panel widths plus labels and gaps stay inside \textwidth
             f"  thesis axis, width={0.94 / n:.2f}\\textwidth, height=0.42\\textwidth,\n"
             # inside groupplot options the key needs its full /pgf path
             "  ybar=0pt, /pgf/bar width=4.5pt, ymin=0, enlarge x limits=0.22,\n"
             "  xtick={1,2,3}, xticklabels={low,medium,high}, xlabel={speed class},\n"
             "  yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=2}]\n")
    for j, (key, title) in enumerate(panels):
        opts = f"title={{{common.tex_escape(title[0])} $\\rightarrow$ {common.tex_escape(title[1])}}}"
        opts += ", ylabel={share of cells}" if j == 0 else ""
        if j == n - 1:
            opts += (", legend style={font=\\small, cells={anchor=west}, at={(1,-0.22)}, anchor=north east, "
                     "legend columns=3}")
        t.append(f"\\nextgroupplot[{opts}]\n")
        for sym, grey, word in SYMPTOMS:
            for role, dash in (("before", "solid"), ("after", "dashed")):
                leg = j == n - 1
                t.append(f"\\addplot[fill={grey}, draw=black, {dash}{'' if leg else ', forget plot'}] "
                         f"table[x=x, y={sym.lower()}_{role}]{{\\tblBal{_macro(key)}}};\n")
                if leg:
                    t.append(f"\\addlegendentry{{{word}, {role}}}\n")
    t.append("\\end{groupplot}\n\\end{tikzpicture}\n")
    return "".join(t)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pair", action="append", required=True, help="BEFORE,AFTER outing IDs")
    ap.add_argument("--tag", default="dev")
    ap.add_argument("--allow-status", action="store_true")
    ap.add_argument("--allow-excluded", action="store_true")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    pairs = [tuple(int(x) for x in p.split(",")) for p in a.pair]
    build(pairs, a.tag, a.allow_status, a.allow_excluded, a.out)


if __name__ == "__main__":
    main()
