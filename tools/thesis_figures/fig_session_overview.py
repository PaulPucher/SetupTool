# fig:session_overview -- per session three bars: the per-lap cell share of
# front limiting (US), rear limiting (OS) and open-loop instability (INST),
# k / n from the stored session cell counts (setup_engine.data_layer.session
# .cells, written by setup_engine.cell_shares: per lap and corner phase, no
# repetition rule; US / OS over the cells with a CS value on that axle, INST
# over the cells with a stability value). Above each bar the number of
# counted symptoms of that type (repeated on a majority of the analysis laps
# and on at least two, the corners that vote: setup_engine.data_layer
# .corners, low-priority corners left out). Below the axis the analysis laps
# and a mark on sessions with development overlap (tab_sessions.csv).
# Stored results only.
# Run: python -m tools.thesis_figures.fig_session_overview --outings 17,18,19,20,21,22,25,26,27,28
#      --separator-after 21 [--tag final] [--out DIR] | --render-only

import argparse

from tools.thesis_figures import common
from tools.thesis_figures.fig_k_sessions import collect

SCRIPT = "fig_session_overview"
TYPES = (("US", "us"), ("OS", "os"), ("INST", "inst"))
STYLE = {"us": "fill=axleFront", "os": "fill=axleRear", "inst": "fill=black!80"}
WORD = {"us": "front limiting (US)", "os": "rear limiting (OS)", "inst": "open-loop unstable (INST)"}
BAR_W, BAR_SHIFT, TRACK_GAP = 0.24, 0.26, 0.7   # axis units; layout only
OVERLAP_MARK = "$^\\dagger$"


def counted_by_type(payload):
    # the vote's input: counted symptoms of the corners that vote
    n = {"US": 0, "OS": 0, "INST": 0}
    for c in payload["setup_engine"]["data_layer"]["corners"]:
        if c.get("low_priority"):
            continue
        for s in c["symptoms"]:
            n[s["symptom"]] += 1
    return n


def build(outings, separator_after=None, tag="dev", out=None):
    rows = collect(outings)
    common.write_label_map(tag, outings)
    data_dir, _plots, _prefix = common.out_dirs(out)
    _m, t1 = common.read_csv(f"{data_dir}/tab_sessions.csv")
    overlap = dict(zip(t1["label"], t1["dev_overlap"]))
    cols = {k: [] for k in ["x", "session", "laps", "overlap"]
            + [f"{p}_{q}" for _t, p in TYPES for q in ("k", "n", "share", "counted")]}
    x = 0.0
    for o, session, _man, _marks in rows:
        payload, _why = common.stored_payload(session)
        label = common.session_label(session["row"])
        cells = payload["setup_engine"]["data_layer"]["session"]["cells"]
        counted = counted_by_type(payload)
        x += 1.0
        for k, v in (("x", x), ("session", label), ("laps", len(payload["lap_filter"])),
                     ("overlap", overlap.get(label, "-"))):
            cols[k].append(v)
        for t, p in TYPES:
            cols[f"{p}_k"].append(cells[t]["k"])
            cols[f"{p}_n"].append(cells[t]["n"])
            cols[f"{p}_share"].append(cells[t]["share"] if cells[t]["share"] is not None else float("nan"))
            cols[f"{p}_counted"].append(counted[t])
        if o == separator_after:
            x += TRACK_GAP
    common.write_csv(f"{data_dir}/{SCRIPT}.csv", cols,
                     common.meta(SCRIPT, outings, tag, source="stored setup_engine.data_layer.session.cells (k, n); "
                                 "counted = symptoms of the voting corners (data_layer.corners)",
                                 caption_note=f"{OVERLAP_MARK} on a session label = development overlap "
                                              "(same file or same session as a development outing)"))
    render(out)
    return cols


def render(out=None):
    data_dir, plots_dir, _prefix = common.out_dirs(out)
    _meta, c = common.read_csv(f"{data_dir}/{SCRIPT}.csv")
    xs = [float(v) for v in c["x"]]
    shares = {p: [100 * common.num(v) for v in c[f"{p}_share"]] for _t, p in TYPES}
    y_max = max(max(v for v in s if v == v) for s in shares.values()) * 1.25
    ticks = []
    for i, lab in enumerate(c["session"]):
        mark = OVERLAP_MARK if c["overlap"][i] not in ("none", "-") else ""
        ticks.append(f"{common.tex_escape(lab)}{mark}\\\\{c['laps'][i]} laps")
    t = ["% generated by tools/thesis_figures/fig_session_overview.py -- do not edit; re-run the script\n",
         "\\begin{tikzpicture}\n",
         "\\begin{axis}[thesis axis, ybar, width=\\textwidth, height=0.42\\textwidth,\n"
         f"  bar width={BAR_W}, xmin={xs[0] - 0.6:.2f}, xmax={xs[-1] + 0.6:.2f}, ymin=0, ymax={y_max:.3g},\n"
         f"  xtick={{{','.join(f'{x:g}' for x in xs)}}}, xticklabels={{{','.join('{' + k + '}' for k in ticks)}}},\n"
         "  xticklabel style={align=center}, xmajorgrids=false,\n"
         "  yticklabel style={/pgf/number format/fixed},\n"
         "  ylabel={share of per-lap cells in \\%},\n"
         "  legend style={at={(0.5,1.03)}, anchor=south, legend columns=3, cells={anchor=west},\n"
         "    /tikz/every even column/.append style={column sep=0.8em}}]\n"]
    for j, (_t, p) in enumerate(TYPES):
        shift = (j - 1) * BAR_SHIFT
        pts = " ".join(f"({x:g},{y:.4g})" for x, y in zip(xs, shares[p]) if y == y)
        t.append(f"\\addplot[{STYLE[p]}, draw=none, bar shift={shift:g}] coordinates {{{pts}}};\n"
                 f"\\addlegendentry{{{WORD[p]}}}\n")
    for j, (_t, p) in enumerate(TYPES):
        shift = (j - 1) * BAR_SHIFT
        for x, y, n in zip(xs, shares[p], c[f"{p}_counted"]):
            if int(n) > 0:
                t.append(f"\\node[anchor=south, inner sep=1pt] at (axis cs:{x + shift:g},{y:.4g}) {{{n}}};\n")
    t.append("\\end{axis}\n\\end{tikzpicture}\n")
    common.write_tex(f"{plots_dir}/{SCRIPT}.tex", "".join(t))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outings", help="comma-separated app outing IDs, in plot order")
    ap.add_argument("--separator-after", type=int, help="outing ID after which the track gap is drawn")
    ap.add_argument("--tag", default="dev")
    ap.add_argument("--out")
    ap.add_argument("--render-only", action="store_true", help="write the .tex from the existing CSV only")
    a = ap.parse_args(argv)
    if a.render_only:
        render(a.out)
        return
    if not a.outings:
        ap.error("--outings is required unless --render-only")
    build([int(x) for x in a.outings.split(",")], a.separator_after, a.tag, a.out)


if __name__ == "__main__":
    main()
